Import("env")
# C3HT EU build pre-script (only listed in the C3HTEU_* envs, after build_flags.py).
#  1. refuses defines that the EU build must not have (home Wi-Fi, static AP
#     password, Wi-Fi at boot, debug logging in release builds);
#  2. strips home-Wi-Fi keys from the options JSON;
#  3. generates include/c3ht_eu_pubkeys.h from PUBLIC key PEM files only;
#  4. generates include/WebContentEU.h from html/c3ht_eu/ (+ shared 3D assets).
# Python stdlib only (runs inside PlatformIO's interpreter).
import base64
import gzip
import hashlib
import io
import os
import re
import sys

from minify import (html_minifier, rcssmin, rjsmin)

FORBIDDEN = ["HOME_WIFI_SSID", "HOME_WIFI_PASSWORD", "MY_AP_PASSWORD", "AUTO_WIFI_ON_INTERVAL", "DEBUG_ELRS_WIFI"]
P256_SPKI_PREFIX = bytes.fromhex("3059301306072a8648ce3d020106082a8648ce3d030107034200")


def fail(msg):
    sys.stderr.write("\n*** C3HT EU build: %s ***\n\n" % msg)
    env.Exit(1)


flags = [str(f) for f in env.get("BUILD_FLAGS", [])]


def has_define(name):
    pat = re.compile(r"(^|\s)-D\s*%s(=|\s|$)" % re.escape(name))
    return any(pat.search(f) for f in flags)


for name in FORBIDDEN:
    if has_define(name):
        fail("-D%s is not allowed in an EU build (DESIGN.md section 3/5)" % name)
release = has_define("C3HT_EU_RELEASE")
if release and (has_define("DEBUG_LOG") or has_define("DEBUG_LOG_VERBOSE")):
    fail("DEBUG_LOG is not allowed in a C3HT_EU_RELEASE build")
if not has_define("C3HT_EU_BUILD"):
    fail("c3ht_eu_pre.py used in an env without -D C3HT_EU_BUILD")

opts = env.get("OPTIONS_JSON", {})
for k in ("wifi-ssid", "wifi-password", "wifi-on-interval"):
    opts.pop(k, None)
env["OPTIONS_JSON"] = opts


def write_if_changed(path, text):
    old = None
    if os.path.exists(path):
        with open(path, "r", encoding="utf-8") as f:
            old = f.read()
    if old != text:
        with open(path, "w", encoding="utf-8", newline="\n") as f:
            f.write(text)


# ---------------------------------------------------------------- public keys
def load_pubkey(path):
    with open(path, "r", encoding="ascii") as f:
        text = f.read()
    if "PRIVATE KEY" in text:
        fail("%s contains a PRIVATE key. Only public keys may be given to the build." % path)
    m = re.search(r"-----BEGIN PUBLIC KEY-----(.*?)-----END PUBLIC KEY-----", text, re.S)
    if not m:
        fail("%s: no PUBLIC KEY block" % path)
    der = base64.b64decode("".join(m.group(1).split()))
    if len(der) != 91 or not der.startswith(P256_SPKI_PREFIX) or der[26] != 4:
        fail("%s: not an uncompressed ECDSA P-256 public key" % path)
    point = der[26:]
    lab = re.search(r"^C3HT-KEY-LABEL:\s*(\S+)", text, re.M)
    label = lab.group(1) if lab else os.path.basename(path)
    dev = "DEV" in label.upper() or "DEV" in os.path.basename(path).upper()
    return {"point": point, "id": hashlib.sha256(point).digest()[:8], "label": label, "dev": dev, "path": path}


key_paths = os.environ.get("C3HT_EU_PUBKEYS", "")
if not key_paths:
    try:
        key_paths = env.GetProjectOption("custom_c3ht_eu_pubkeys", "")
    except Exception:
        key_paths = ""
if not key_paths and os.path.exists(os.path.join("keys", "c3ht_eu_release_pub.pem")):
    key_paths = os.path.join("keys", "c3ht_eu_release_pub.pem")
keys = [load_pubkey(p.strip()) for p in re.split(r"[;\n]", key_paths) if p.strip()]
if release and not keys:
    fail("C3HT_EU_RELEASE needs a release public key (C3HT_EU_PUBKEYS or keys/c3ht_eu_release_pub.pem)")
if release and any(k["dev"] for k in keys):
    fail("C3HT_EU_RELEASE build with a DEV key: %s" % ", ".join(k["label"] for k in keys if k["dev"]))
if len(set(k["id"] for k in keys)) != len(keys):
    fail("duplicate public key")

lines = ["// GENERATED by python/c3ht_eu_pre.py - public keys only, do not edit",
         "#pragma once", "#include <stdint.h>",
         "typedef struct { uint8_t id[8]; uint8_t point[65]; uint8_t dev; const char *label; } c3ht_eu_pubkey_t;",
         "#define C3HT_EU_PUBKEY_COUNT %d" % len(keys),
         '#define C3HT_EU_KEY_IDS_STR "%s"' % ",".join(k["id"].hex() for k in keys),
         "#define C3HT_EU_HAS_DEV_KEY %d" % (1 if any(k["dev"] for k in keys) else 0),
         "static const c3ht_eu_pubkey_t C3HT_EU_PUBKEYS[%d] = {" % max(1, len(keys))]
for k in keys:
    lines.append("  {{%s}, {%s}, %d, \"%s\"}," % (",".join("0x%02x" % b for b in k["id"]),
                                                  ",".join("0x%02x" % b for b in k["point"]),
                                                  1 if k["dev"] else 0, k["label"]))
if not keys:
    lines.append("  {{0}, {0}, 0, \"none\"},")
lines.append("};")
write_if_changed(os.path.join("include", "c3ht_eu_pubkeys.h"), "\n".join(lines) + "\n")
if keys:
    for k in keys:
        sys.stdout.write("\u001b[32mC3HT EU OTA public key %s (%s)%s\n" % (k["id"].hex(), k["label"],
                                                                       "  [DEV KEY]" if k["dev"] else ""))
else:
    sys.stdout.write("\u001b[33mC3HT EU: no public key given (C3HT_EU_PUBKEYS) - OTA disabled, USB updates only\n")


# ---------------------------------------------------------------- web content
def gz(data):
    buf = io.BytesIO()
    with gzip.GzipFile(fileobj=buf, mode="wb", compresslevel=9, mtime=0.0) as f:
        f.write(data)
    return buf.getvalue()


def c_array(name, data):
    return "static const uint8_t PROGMEM %s[] = {\n%s\n};\n\n" % (name, ",".join("0x%02x" % c for c in data))


version = "%s (%s)" % (env.get("GIT_VERSION"), env.get("GIT_SHA"))
out = ["// GENERATED by python/c3ht_eu_pre.py from html/c3ht_eu - do not edit\n#pragma once\n#include <Arduino.h>\n",
       'const char *VERSION = "%s";\n\n' % version]
with open("html/c3ht_eu/index.html", "r", encoding="utf-8") as f:
    html = html_minifier.html_minify(f.read()).replace("@VERSION@", version)
out.append(c_array("EU_INDEX_HTML", gz(html.encode())))
with open("html/c3ht_eu/eu.js", "r", encoding="utf-8") as f:
    out.append(c_array("EU_JS", gz(rjsmin.jsmin(f.read()).encode())))
with open("html/c3ht_eu/eu.css", "r", encoding="utf-8") as f:
    out.append(c_array("EU_CSS", gz(rcssmin.cssmin(f.read()).encode())))
with open("html/p5.js", "r", encoding="ISO-8859-1") as f:
    out.append(c_array("EU_P5_JS", gz(rjsmin.jsmin(f.read()).encode("utf-8"))))
with open("html/airplane.obj", "rb") as f:
    out.append(c_array("EU_PLANE_OBJ", gz(f.read())))
with open("html/texture.gif", "rb") as f:
    out.append(c_array("EU_TEXTURE_GIF", f.read()))
write_if_changed(os.path.join("include", "WebContentEU.h"), "".join(out))
