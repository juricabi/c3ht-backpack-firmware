static void sendStatic(AsyncWebServerRequest *r, const char *type, const uint8_t *data, size_t len, bool gz)
{
    if (!hostOk(r)) {
        r->redirect("http://10.0.0.1/");
        return;
    }
    AsyncWebServerResponse *resp = r->beginResponse_P(200, type, data, len);
    if (gz) resp->addHeader("Content-Encoding", "gzip");
    r->send(resp);
}

