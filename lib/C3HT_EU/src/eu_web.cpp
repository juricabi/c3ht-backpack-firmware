static void onNotFound(AsyncWebServerRequest *r)
{
    if (!hostOk(r)) {
        // DNS-rebinding / captive-portal browsers: GET is redirected, nothing else is served.
        if (r->method() == HTTP_GET) r->redirect("http://10.0.0.1/");
        else r->send(403, "text/plain", "forbidden");
        return;
    }
    if (r->url().startsWith("/api/") || r->url() == "/ws") {
        r->send(401, "application/json", "{\"ok\":false,\"msg\":\"login required\"}");
        return;
    }
    r->send(404, "text/plain", "not found");   // never echoes the request
}

static void newSession(AsyncWebServerRequest *r)
{
    char sidhex[33], csrfhex[33];
    euRandom(sess.sid, 16);
    euRandom(sess.csrf, 16);
    sess.created = sess.last = millis();
    sess.valid = true;
    lastAuthMs = sess.created;
    ws.closeAll();
    wsAuthedId = 0;
    euHex(sess.sid, 16, sidhex);
    euHex(sess.csrf, 16, csrfhex);
    JsonDocument d;
    d["ok"] = true;
    d["csrf"] = csrfhex;
    d["default_pw"] = !euUserPasswordSet();
    AsyncResponseStream *resp = r->beginResponseStream("application/json");
    resp->addHeader("Set-Cookie", String("c3ht_sid=") + sidhex + "; HttpOnly; SameSite=Strict; Path=/");
    serializeJson(d, *resp);
    r->send(resp);
    euWipe(sidhex, sizeof(sidhex));
}

static void onLogin(AsyncWebServerRequest *r)
{
    if (lockedOut(r)) return;
    JsonDocument doc;
    if (!parseBody(r, doc)) {
        wipeBody(r);
        sendErr(r, 400, "bad request");
        return;
    }
    const char *pw = doc["password"] | "";
    bool ok = euCheckLogin(pw);
    wipeBody(r);
    doc.clear();
    if (!ok) {
        noteFailure();
        sendErr(r, 401, "wrong password");
        return;
    }
    failCount = 0;
    lockUntil = 0;
    euLogEvent(EV_LOGIN_OK, 0, false);
    newSession(r);
}

static void onSession(AsyncWebServerRequest *r)
{
    touch();
    char csrfhex[33];
    euHex(sess.csrf, 16, csrfhex);
    JsonDocument d;
    d["ok"] = true;
    d["csrf"] = csrfhex;
    d["default_pw"] = !euUserPasswordSet();
    sendJson(r, 200, d);
}

static void onLogout(AsyncWebServerRequest *r)
{
    euWebEndSessions();
    AsyncWebServerResponse *resp = r->beginResponse(200, "application/json", "{\"ok\":true}");
    resp->addHeader("Set-Cookie", "c3ht_sid=; Max-Age=0; HttpOnly; SameSite=Strict; Path=/");
    r->send(resp);
}

