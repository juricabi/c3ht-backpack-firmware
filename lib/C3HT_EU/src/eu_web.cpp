uint32_t euApRemainingS()
{
    if (!apUp) return 0;
    uint32_t now = millis();
    uint32_t a = AP_NO_CLIENT_MS - (now - lastClientMs);
    uint32_t b = AP_IDLE_AUTH_MS - (now - lastAuthMs);
    uint32_t c = AP_TOTAL_MS - (now - apStartMs);
    uint32_t m = a < b ? a : b;
    m = m < c ? m : c;
    return (int32_t)m > 0 ? m / 1000 : 0;
}

void euWebEndSessions()
{
    sess.valid = false;
    euWipe(sess.sid, sizeof(sess.sid));
    euWipe(sess.csrf, sizeof(sess.csrf));
    if (apUp) ws.closeAll();
    wsAuthedId = 0;
}

// ---------------------------------------------------------------- request checks
static bool hostOk(AsyncWebServerRequest *r)
{
    const String &h = r->host();
    return h == "10.0.0.1" || h == "10.0.0.1:80";
}

static bool originOk(AsyncWebServerRequest *r)
{
    // Browsers send Origin on every POST/WebSocket; scripted clients
    // (python/c3ht_eu_upload.py) send no Origin but the custom X-C3HT header,
    // which a cross-site page cannot add without a CORS preflight we never answer.
    if (!r->hasHeader("Origin")) return r->hasHeader("X-C3HT");
    String o = r->header("Origin");
    return o == "http://10.0.0.1" || o == "http://10.0.0.1:80";
}

static bool sessionLive(uint32_t now)
{
    if (!sess.valid) return false;
    if (now - sess.created > SESSION_MAX_MS || now - sess.last > SESSION_IDLE_MS) {
        euWebEndSessions();
        return false;
    }
    return true;
}

static bool cookieOk(AsyncWebServerRequest *r)
{
    if (!sessionLive(millis()) || !r->hasHeader("Cookie")) return false;
    String c = r->header("Cookie");
    int i = 0;
    while ((i = c.indexOf("c3ht_sid=", i)) >= 0) {
        if (i == 0 || c[i - 1] == ' ' || c[i - 1] == ';') break;
        i++;
    }
    if (i < 0) return false;
    String v = c.substring(i + 9, i + 9 + 32);
    uint8_t sid[16];
    if (!euUnhex(v.c_str(), sid, 16)) return false;
    bool ok = euCtEqual(sid, sess.sid, 16);
    euWipe(sid, sizeof(sid));
    return ok;
}

static bool csrfOk(AsyncWebServerRequest *r)
{
    if (!r->hasHeader("X-C3HT-CSRF")) return false;
    uint8_t t[16];
    if (!euUnhex(r->header("X-C3HT-CSRF").c_str(), t, 16)) return false;
    return euCtEqual(t, sess.csrf, 16);
}

static void touch()
{
    uint32_t now = millis();
    sess.last = now;
    lastAuthMs = now;
}

// Filters run when the headers are complete and BEFORE any body byte is passed
// to a handler, so an unauthenticated upload never reaches esp_ota_begin().
static bool fGet(AsyncWebServerRequest *r) { return hostOk(r) && cookieOk(r); }
static bool fPost(AsyncWebServerRequest *r) { return hostOk(r) && originOk(r) && cookieOk(r) && csrfOk(r); }
static bool fLogin(AsyncWebServerRequest *r)
{
    return hostOk(r) && originOk(r) && r->contentType() == "application/json";
}
static bool fUpdate(AsyncWebServerRequest *r)
{
    return fPost(r) && r->contentType() == "application/octet-stream";
}
static bool fWs(AsyncWebServerRequest *r)
{
    return hostOk(r) && r->hasHeader("Origin") && originOk(r) && cookieOk(r);
}

// ---------------------------------------------------------------- helpers
struct Body {
    uint16_t len;
    bool over;
    char buf[BODY_MAX + 1];
};

static void collectBody(AsyncWebServerRequest *r, uint8_t *data, size_t len, size_t index, size_t total)
{
    if (index == 0 && !r->_tempObject) {
        Body *b = (Body *)calloc(1, sizeof(Body));
        if (!b) return;
        b->over = total > BODY_MAX;
        r->_tempObject = b;
    }
    Body *b = (Body *)r->_tempObject;
    if (!b || b->over) return;
    if (index + len > BODY_MAX) {
        b->over = true;
        return;
    }
    memcpy(b->buf + index, data, len);
    b->len = index + len;
}

static void wipeBody(AsyncWebServerRequest *r)
{
    if (r->_tempObject) euWipe(r->_tempObject, sizeof(Body));
}

static void sendJson(AsyncWebServerRequest *r, int code, JsonDocument &doc)
{
    AsyncResponseStream *resp = r->beginResponseStream("application/json");
    resp->setCode(code);
    serializeJson(doc, *resp);
    r->send(resp);
}

static void sendErr(AsyncWebServerRequest *r, int code, const char *msg)
{
    JsonDocument d;
    d["ok"] = false;
    d["msg"] = msg;
    sendJson(r, code, d);
}

static bool parseBody(AsyncWebServerRequest *r, JsonDocument &doc)
{
    Body *b = (Body *)r->_tempObject;
    if (!b || b->over || b->len == 0) return false;
    b->buf[b->len] = 0;
    return !deserializeJson(doc, b->buf, b->len);
}

static bool lockedOut(AsyncWebServerRequest *r)
{
    uint32_t now = millis();
    if (lockUntil && (int32_t)(now - lockUntil) < 0) {
        AsyncWebServerResponse *resp = r->beginResponse(429, "application/json",
                                                        "{\"ok\":false,\"msg\":\"too many attempts\"}");
        resp->addHeader("Retry-After", String((lockUntil - now) / 1000 + 1));
        r->send(resp);
        return true;
    }
    return false;
}

static void noteFailure()
{
    failCount++;
    euLogEvent(EV_LOGIN_FAIL, 0, false);
    if (failCount >= LOCKOUT_AFTER) {
        uint32_t shift = failCount - LOCKOUT_AFTER;
        uint32_t d = shift > 5 ? LOCKOUT_MAX_MS : LOCKOUT_BASE_MS << shift;
        if (d > LOCKOUT_MAX_MS) d = LOCKOUT_MAX_MS;
        lockUntil = millis() + d;
        if (lockUntil == 0) lockUntil = 1;
        euLogEvent(EV_LOCKOUT, (uint16_t)(d / 1000), true);
    }
}

// Checks the current password for a state-changing request; counts toward the lockout.
static bool reauth(AsyncWebServerRequest *r, JsonDocument &doc)
{
    const char *cur = doc["current"] | "";
    if (euCheckLogin(cur)) return true;
    noteFailure();
    sendErr(r, 403, "current password is wrong");
    return false;
}

